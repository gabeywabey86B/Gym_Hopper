create table public.gym_enrichments (
  id bigint generated by default as identity primary key,
  postal_code text not null,
  facility_type text not null,
  equipment text[] not null default ARRAY[]::text[],
  amenities text[] not null default ARRAY[]::text[],
  day_pass_price numeric,
  membership_price numeric,
  created_at timestamptz not null default now(),
  unique (postal_code, facility_type)
);

alter table public.gym_enrichments enable row level security;

create policy "Allow public read gym enrichments"
on public.gym_enrichments
for select
to anon
using (true);
